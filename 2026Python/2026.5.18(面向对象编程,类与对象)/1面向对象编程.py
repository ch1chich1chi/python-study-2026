# 面向过程编程
# 核心思想:把一个需求拆成一系列要执行的步骤,然后按照步骤依次执行这些任务(关注的是流程 步骤)

# 面向对象编程
# 对象可以理解为现实中具体的人/物在程序中的数字化身(万物皆对象)
# 他把一个人/物的特征和功能打包到一起,是面向对象编程的基本单元(关注的是谁来帮我做这件事)
# 对象的特征称为:属性
# 对象的功能称为:方法

# 面向对象编程 --- 类与对象
# 类:描述的是一组具有相同属性(特征)和方法(功能/行为)的模板
# 对象:对象是类的实例,是基于类创建出来的(实例对象)
# 提示;对象是由类创建出来的,创建对象的过程,也称为对象的实例化 一个类可以创建无数个对象